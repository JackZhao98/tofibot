// Opt-in with TOFI_METADATA_API and TOFI_METADATA_ORIGIN. All data is synthetic.
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const backend = process.env.TOFI_METADATA_API;
assert.ok(backend, "TOFI_METADATA_API must name the isolated synthetic fixture");
const origin = process.env.TOFI_METADATA_ORIGIN || "http://127.0.0.1:5198";
const output = resolve(process.env.TOFI_METADATA_OUTPUT || "../docs/acceptance/display-metadata");
await mkdir(output, { recursive: true });
const fixture = await (await fetch(backend + "/acceptance/context")).json();
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
const results = [];
try {
  for (const [name, width, native] of [["mobile", 390, false], ["tablet", 820, false], ["desktop", 1280, false], ["native-row", 1280, true]]) {
    const context = await browser.newContext({ viewport: { width, height: 950 } });
    await context.addInitScript(({ fixture, native }) => { window.metadataFixture = fixture; if (native) window.tofiDesktop = { platform: "darwin", onFlushState: () => () => {}, onWindowState: () => () => {}, remoteInputFocus: () => {} }; }, { fixture, native });
    const page = await context.newPage();
    const errors = []; page.on("pageerror", error => errors.push(error.message));
    await page.goto(origin + "/test-fixtures/metadata.html");
    const rows = page.locator(native ? ".scheduled-task-row" : ".scheduled-run");
    await rows.first().waitFor(); assert.equal(await rows.count(), 3);
    assert.doesNotMatch(await page.locator("#runs").innerText(), /EXECUTION_PROMPT_SENTINEL/);
    assert.match(await page.locator("#runs").innerText(), /标题 once/);
    assert.match(await page.locator("#runs").innerText(), /说明 once/);
    await page.screenshot({ path: `${output}/${name}-runs-collapsed.png`, fullPage: true });
    assert.ok(!(await page.locator("#runs [title]").evaluateAll(nodes => nodes.map(node => node.title))).some(value => value.includes("SENTINEL")), "compact tooltip leaked prompt");
    await rows.first().locator(native ? ":scope > details > summary" : ".scheduled-run-toggle").click();
    assert.doesNotMatch(await rows.first().innerText(), /EXECUTION_PROMPT_SENTINEL/, "expanding status details must still keep prompt in management");
    await rows.first().getByText("管理 · 完整执行指令", { exact: true }).click();
    assert.match(await rows.first().innerText(), /EXECUTION_PROMPT_SENTINEL/);
    await page.getByRole("button", { name: "预览", exact: true }).click();
    await page.locator("#preview small").filter({ hasText: /标题/ }).waitFor();
    assert.doesNotMatch(await page.locator("#preview").innerText(), /SENTINEL/);
    await page.getByRole("button", { name: "日程列表", exact: true }).click();
    await page.locator(".work-schedule").first().waitFor();
    assert.equal(await page.locator(".work-schedule").count(), 4);
    assert.doesNotMatch(await page.locator("#schedules").innerText(), /SENTINEL/);
    assert.match(await page.locator("#schedules").innerText(), /定时任务/);
    await page.getByRole("button", { name: "记忆列表", exact: true }).click();
    await page.locator(".memory-card").first().waitFor();
    assert.doesNotMatch(await page.locator(".memory-list").innerText(), /MEMORY_BODY_SENTINEL/);
    assert.match(await page.locator(".memory-list").innerText(), /饮品偏好/);
    await page.getByRole("searchbox", { name: "搜索记忆" }).fill("東京");
    assert.equal(await page.locator(".memory-card").count(), 1, "search must include full factual body without exposing it");
    await page.getByText("查看完整记忆", { exact: true }).click();
    assert.match(await page.locator(".memory-card").innerText(), /用户喜欢茶/);
    await page.getByRole("searchbox", { name: "搜索记忆" }).fill("");
    assert.equal(await page.locator(".memory-card").count(), 2);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "horizontal overflow");
    assert.deepEqual(errors, []);
    await page.locator(".memory-details").first().evaluate(element => { element.open = false; });
    await page.screenshot({ path: `${output}/${name}-memories.png`, fullPage: true });
    results.push({ name, pass: true, checks: "compact labels, descriptions, tooltips, management-only prompt, preview, all schedule kinds, legacy fallback, multilingual memory search/details, viewport" });
    await context.close();
  }

  // Actual UI edits/create/reload followed by a real SQLite server restart.
  const context = await browser.newContext({ viewport: { width: 1280, height: 950 } });
  await context.addInitScript(fixture => { window.metadataFixture = fixture; }, fixture);
  const page = await context.newPage();
  await page.goto(origin + "/test-fixtures/metadata.html");
  await page.getByRole("button", { name: "记忆列表", exact: true }).click();
  await page.locator(".memory-card").first().getByRole("button", { name: "编辑", exact: true }).click();
  const body = await page.getByRole("textbox", { name: "编辑记忆", exact: true }).inputValue();
  await page.getByRole("textbox", { name: "编辑记忆标题" }).fill("更新的偏好标题");
  await page.getByRole("textbox", { name: "编辑记忆说明" }).fill("更新说明；事实原文不变。");
  await page.locator(".memory-edit").getByRole("button", { name: "保存", exact: true }).click();
  await page.getByText("更新的偏好标题", { exact: true }).waitFor();
  await page.getByRole("textbox", { name: "新增记忆标题" }).fill("新记忆");
  await page.getByRole("textbox", { name: "新增记忆说明" }).fill("用户提供的新事实。");
  await page.getByRole("textbox", { name: "新增记忆", exact: true }).fill("新增事实：中文原文 preserved.");
  await page.getByRole("button", { name: "保存记忆", exact: true }).click();
  await page.getByText("新记忆", { exact: true }).waitFor();
  await page.getByRole("button", { name: "日程列表", exact: true }).click();
  const row = page.locator(".work-schedule").filter({ has: page.getByText("标题 daily", { exact: true }) });
  await row.locator(":scope > details > summary").click();
  await row.getByRole("button", { name: "编辑", exact: true }).click();
  const instruction = await page.getByRole("textbox", { name: "编辑日程执行指令" }).inputValue();
  await page.getByRole("textbox", { name: "编辑日程标题" }).fill("更新的日程标题");
  await page.getByRole("textbox", { name: "编辑日程说明" }).fill("更新日程说明。");
  await row.getByRole("button", { name: "保存", exact: true }).click();
  await page.getByText("更新的日程标题", { exact: true }).waitFor();
  await page.screenshot({ path: `${output}/desktop-schedules-edited.png`, fullPage: true });
  const edited = await (await fetch(backend + "/acceptance/context")).json();
  const oldPlan = fixture.schedules.find(item => item.kind === "daily");
  const newPlan = edited.schedules.find(item => item.id === oldPlan.id);
  for (const key of ["id", "content", "next_at_utc", "timezone", "kind", "daily_time", "interval_seconds", "created_at"]) assert.equal(newPlan[key], oldPlan[key], `metadata edit changed ${key}`);
  assert.equal(newPlan.content, instruction);
  assert.equal(edited.memories.find(item => item.id === fixture.memories[0].id).content, body);
  assert.equal(edited.occurrences.find(item => item.schedule_id === oldPlan.id).title, "标题 daily");
  assert.equal(edited.occurrences.find(item => item.schedule_id === oldPlan.id).description, "说明 daily：简短的用户说明。");
  assert.equal((await fetch(backend + "/acceptance/restart", { method: "POST" })).status, 200);
  await page.reload();
  await page.getByRole("button", { name: "记忆列表", exact: true }).click();
  await page.getByText("更新的偏好标题", { exact: true }).waitFor();
  await page.getByText("新记忆", { exact: true }).waitFor();
  await page.getByRole("button", { name: "日程列表", exact: true }).click();
  await page.getByText("更新的日程标题", { exact: true }).waitFor();
  await page.getByRole("button", { name: "执行卡", exact: true }).click();
  await page.getByText("标题 daily", { exact: true }).waitFor();
  assert.doesNotMatch(await page.locator("#runs").innerText(), /更新的日程标题|EXECUTION_PROMPT_SENTINEL/);
  results.push({ name: "persistence", pass: true, checks: "UI create/edit, exact factual body/prompt preservation, timing unchanged, immutable occurrence snapshot, reload and SQLite restart" });
  await context.close();
  await writeFile(`${output}/browser-results.json`, JSON.stringify(results, null, 2));
  console.log("PASS: 4 rendered Chrome layouts + UI creation/editing/reload/SQLite restart; no compact prompt leaks");
} finally { await browser.close(); }
